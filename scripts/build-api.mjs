// Bundles each route in server/ into one self contained file in api/.
// Vercel then runs plain JavaScript with no imports to resolve.
// Run after changing anything in server/ or src/engine/:  npm run build:api
import { build } from 'esbuild'

const routes = ['daily', 'auth', 'submit', 'leaderboard', 'share', 'health']
for (const r of routes) {
  await build({
    entryPoints: [`server/${r}.ts`],
    outfile: `api/${r}.js`,
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node18',
    logLevel: 'warning',
    banner: { js: '// GENERATED by scripts/build-api.mjs from server/' + r + '.ts. Do not edit.' },
    footer: { js: 'module.exports = module.exports.default;' },
  })
}
console.log('api built:', routes.join(', '))
